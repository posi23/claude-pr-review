"""
peer_review.py

Sends the PR diff (plus test results) to Claude and asks for a peer code review.
Outputs a markdown file ready to be posted as a GitHub PR comment.

Claude will NEVER suggest direct changes — only observations and recommendations.
All code changes require explicit developer approval.
"""

import argparse
import json
import subprocess
from pathlib import Path

# ── Prompt ────────────────────────────────────────────────────────────────────

SYSTEM_PROMPT = """You are a thorough but constructive senior engineer doing a peer code review.

Your job:
- Review the PR diff critically but fairly, as a knowledgeable colleague would.
- Check for: security vulnerabilities, performance concerns, code style and naming,
  architecture and design patterns, missing error handling, edge cases, and
  anything else a good reviewer would flag.

Hard rules:
- You are an OBSERVER only. You do NOT make changes to any files.
- Frame every finding as an observation or suggestion, never a command.
- Clearly separate blocking issues (bugs, security) from suggestions (style, nits).
- Be specific: reference file names and line context from the diff when possible.
- Keep the tone collegial — you're helping, not judging.
- Do not reproduce large chunks of code; quote only the relevant snippet.
- End with an overall verdict: Approve / Approve with suggestions / Request changes."""


def load_json_results(path: str) -> dict:
    try:
        return json.loads(Path(path).read_text(encoding="utf-8"))
    except Exception:
        return {"summary": "Results unavailable.", "test_output": ""}


def format_test_section(results: dict, label: str) -> str:
    summary = results.get("summary", "No summary available.")
    output = results.get("test_output", "").strip()
    passed = results.get("passed", 0)
    failed = results.get("failed", 0)
    note = results.get("note", "")

    if failed == 0 and passed > 0:
        icon = "✅"
    elif failed > 0:
        icon = "❌"
    else:
        icon = "⚠️"

    lines = [f"### {icon} {label}", f"**{summary}**"]
    if note:
        lines.append(f"_{note}_")
    if output:
        # Cap output to avoid enormous comments
        truncated = output if len(output) < 3000 else output[:3000] + "\n\n… (truncated)"
        lines.append(f"```\n{truncated}\n```")
    return "\n".join(lines)


# ── Main ──────────────────────────────────────────────────────────────────────

def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--diff", required=True)
    parser.add_argument("--python-results", required=True)
    parser.add_argument("--svelte-results", required=True)
    parser.add_argument("--output", required=True)
    args = parser.parse_args()

    diff_text = Path(args.diff).read_text(encoding="utf-8")
    python_results = load_json_results(args.python_results)
    svelte_results = load_json_results(args.svelte_results)

    # Truncate diff if very large to stay within token budget
    max_diff_chars = 20_000
    diff_for_prompt = diff_text
    diff_note = ""
    if len(diff_text) > max_diff_chars:
        diff_for_prompt = diff_text[:max_diff_chars]
        diff_note = "\n\n_(Diff was truncated to ~20 000 chars for context window reasons. Review may be partial.)_"

    user_message = f"""Please review this pull request diff.

=== PR DIFF ===
{diff_for_prompt}

=== PYTHON TEST RESULTS ===
{python_results.get('summary', 'N/A')}

=== FRONTEND TEST RESULTS ===
{svelte_results.get('summary', 'N/A')}

Provide a thorough peer code review using the format below.
Do not suggest making any changes yourself — only flag observations for the developer."""

    print("Calling Claude for peer review...")
    result = subprocess.run(
        ["claude", "-p", f"{SYSTEM_PROMPT}\n\n{user_message}"],
        capture_output=True,
        text=True,
        check=True,
        timeout=180,
    )
    review_text = result.stdout.strip()

    # ── Assemble the full PR comment ──────────────────────────────────────────
    python_section = format_test_section(python_results, "Python Tests (Pytest)")
    svelte_section = format_test_section(svelte_results, "Frontend Tests (Vitest)")

    comment = f"""## 🤖 Claude PR Review

> _This review was generated automatically. All suggestions require **explicit developer approval** before any changes are made._

---

## 🧪 Test Results

{python_section}

{svelte_section}

---

## 👀 Peer Code Review

{review_text}{diff_note}

---
<sub>Generated by Claude · Powered by Anthropic · Changes require your approval</sub>
"""

    Path(args.output).write_text(comment, encoding="utf-8")
    print(f"Review comment written to {args.output}")


if __name__ == "__main__":
    main()
